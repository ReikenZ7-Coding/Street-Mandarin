// Builds why.js: ready-made "Why, exactly?" explanations for every scripted slip.
// Usage: node tools/build-why.js [new.json ...]  (each maps "sid|hanzi|note16" to {why, tip}).
// Run it after editing scenes.js: it keeps existing entries, re-keys them, and lists slips that still need one.
const fs = require("fs"), path = require("path");
global.window = {}; require(path.join(__dirname, "..", "scenes.js"));
const S = window.SCENES, src = {};
// why.js itself is the edited source of truth: hand fixes there survive a rebuild
const whyFile = path.join(__dirname, "..", "why.js");
let kept = {}; try { require(whyFile); kept = window.WHY || {}; } catch {}
process.argv.slice(2).forEach(f => Object.assign(src, JSON.parse(fs.readFileSync(f, "utf8"))));
// Every slip in the scenes, with how often its sid|hanzi repeats (a repeat needs the note to tell them apart)
const slips = [];
S.forEach(s => s.turns.concat((s.curveballs || []).map(c => c.turn)).forEach(t => t.opts.forEach(o => { if (o.k !== "good") slips.push({ sid: s.id, h: o.h, note: o.note }); })));
const count = {}; slips.forEach(x => count[x.sid + "|" + x.h] = (count[x.sid + "|" + x.h] || 0) + 1);
const out = {}, missing = [];
slips.forEach(x => {
  const base = x.sid + "|" + x.h, full = base + "|" + x.note.slice(0, 16);
  // Notes may have been edited since the explanations were written: fall back to any entry for this sid|hanzi
  const hit = kept[base] || kept[full] || src[full] || Object.keys(src).filter(k => k.startsWith(base + "|")).map(k => src[k])[count[base] === 1 ? 0 : -1];
  if (!hit) return missing.push(full);
  out[count[base] === 1 ? base : full] = { why: hit.why, tip: hit.tip };
});
fs.writeFileSync(path.join(__dirname, "..", "why.js"), "// Generated by tools/build-why.js. Ready-made explanations for \"Why, exactly?\", keyed by place|what you said.\nwindow.WHY = " + JSON.stringify(out, null, 0).replace(/\},"/g, '},\n"') + ";\n");
console.log(`${Object.keys(out).length} explanations written, ${missing.length} slips without one`);
if (missing.length) console.log(missing.slice(0, 10).join("\n"));
